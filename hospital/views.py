    appointment = get_object_or_404(models.Appointment, pk=pk, doctorId=request.user.id)
    action = request.POST.get('action')
    allowed = {'approve': 'APPROVED', 'reject': 'REJECTED', 'complete': 'COMPLETED'}
    valid_transitions = {
        'PENDING': {'approve', 'reject'},
        'APPROVED': {'complete'},
    }
    if action not in allowed or action not in valid_transitions.get(appointment.workflow_status, set()):
        messages.error(request, 'That appointment action is not valid for its current status.')
    else:
        appointment.workflow_status = allowed[action]
        appointment.status = action in ('approve', 'complete')
        appointment.save(update_fields=['workflow_status', 'status'])
        patient_user = models.User.objects.filter(pk=appointment.patientId).first()
        notify_user(
            patient_user,
            f'CareNest appointment {appointment.get_workflow_status_display().lower()}',
            f'Your appointment with {appointment.doctorName} on {appointment.scheduled_date} at {appointment.scheduled_time} is now {appointment.get_workflow_status_display().lower()}.',
        )
        messages.success(request, f"Appointment marked {appointment.get_workflow_status_display().lower()}.")
    return redirect('doctor-view-appointment')


