@login_required(login_url='patientlogin')
@user_passes_test(is_patient)
def patient_book_appointment_view(request):
    patient = get_object_or_404(models.Patient, user=request.user, status=True)
    appointment_form = forms.PatientAppointmentForm(request.POST or None)
    if request.method == 'POST' and appointment_form.is_valid():
        doctor = appointment_form.cleaned_data['doctorId']
        scheduled_date = appointment_form.cleaned_data['scheduled_date']
        scheduled_time = appointment_form.cleaned_data['scheduled_time']
        weekday = scheduled_date.weekday()
        available = models.DoctorAvailability.objects.filter(
            doctor=doctor, weekday=weekday, is_active=True,
            start_time__lte=scheduled_time, end_time__gt=scheduled_time,
        ).exists()
        already_booked = models.Appointment.objects.filter(
            doctorId=doctor.user_id, scheduled_date=scheduled_date,
            scheduled_time=scheduled_time,
        ).exclude(workflow_status='REJECTED').exists()
        if not available:
            appointment_form.add_error('scheduled_time', 'This doctor is not available at the selected day and time. Please check the doctor schedule.')
        elif already_booked:
            appointment_form.add_error('scheduled_time', 'This time has already been requested. Please choose another time.')
        else:
            appointment = appointment_form.save(commit=False)
            appointment.doctorId = doctor.user_id
            appointment.patientId = request.user.id
            appointment.doctorName = doctor.get_name[:40]
            appointment.patientName = patient.get_name[:40]
            appointment.status = False
            appointment.workflow_status = 'PENDING'
            appointment.save()
            notify_user(
                doctor.user,
                'New CareNest appointment request',
                f'{patient.get_name} requested an appointment on {scheduled_date} at {scheduled_time}. Please sign in to review it.',
            )
            messages.success(request, 'Appointment request sent. You can track its status under My Appointments.')
            return redirect('patient-view-appointment')
    availability = models.DoctorAvailability.objects.filter(doctor__status=True, is_active=True).select_related('doctor__user')
    return render(request, 'hospital/patient_book_appointment.html', {
        'appointmentForm': appointment_form, 'patient': patient, 'availability': availability,
    })





