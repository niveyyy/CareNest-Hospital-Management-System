def doctor_signup_view(request):
    userForm=forms.DoctorUserForm()
    doctorForm=forms.DoctorForm()
    mydict={'userForm':userForm,'doctorForm':doctorForm}
    if request.method=='POST':
        userForm=forms.DoctorUserForm(request.POST)
        doctorForm=forms.DoctorForm(request.POST,request.FILES)
        if userForm.is_valid() and doctorForm.is_valid():
            with transaction.atomic():
                user = userForm.save(commit=False)
                user.set_password(userForm.cleaned_data['password'])
                user.save()
                doctor = doctorForm.save(commit=False)
                doctor.user = user
                doctor.status = False
                doctor.save()
                doctor_group, _ = Group.objects.get_or_create(name='DOCTOR')
                doctor_group.user_set.add(user)
            messages.success(request, 'Doctor registration submitted. Please wait for admin approval.')
            return redirect('doctorlogin')
        mydict = {'userForm': userForm, 'doctorForm': doctorForm}
    return render(request,'hospital/doctorsignup.html',context=mydict)


def patient_signup_view(request):
    if request.method == 'POST':
        userForm = forms.PatientUserForm(request.POST)
        patientForm = forms.PatientForm(request.POST, request.FILES)

        if userForm.is_valid() and patientForm.is_valid():
            # Create the user, patient profile and role membership together.
            # If any database operation fails, none of them will be left half-created.
            with transaction.atomic():
                user = userForm.save(commit=False)
                user.set_password(userForm.cleaned_data['password'])
                user.save()

                patient = patientForm.save(commit=False)
                patient.user = user
                selected_doctor = patientForm.cleaned_data.get('assignedDoctorId')
                patient.assignedDoctorId = selected_doctor.user_id if selected_doctor else None
                # Only an administrator can approve a newly registered patient.
                patient.status = False
                patient.save()

                patient_group, _ = Group.objects.get_or_create(name='PATIENT')
                patient_group.user_set.add(user)

            messages.success(
                request,
                'Registration submitted successfully. Please sign in; your account will be available after admin approval.'
            )
            return redirect('/patientlogin')
    else:
        userForm = forms.PatientUserForm()
        patientForm = forms.PatientForm()

    has_approved_doctors = patientForm.fields['assignedDoctorId'].queryset.exists()
    return render(request, 'hospital/patientsignup.html', {
        'userForm': userForm,
        'patientForm': patientForm,
        'has_approved_doctors': has_approved_doctors,
    })

def is_admin(user):
    return user.groups.filter(name='ADMIN').exists()
def is_doctor(user):
    return user.groups.filter(name='DOCTOR').exists()
def is_patient(user):
    return user.groups.filter(name='PATIENT').exists()


def notify_user(user, subject, body):
    """Send a notification when an account has a registered email address."""
    if user and user.email:
        send_mail(
            subject,
            body,
            getattr(settings, 'DEFAULT_FROM_EMAIL', 'noreply@carenest.local'),
            [user.email],
            fail_silently=True,
        )


